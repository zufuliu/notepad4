enum SqlOption {
	SqlOption_BackticksIdentifier = 1,
	SqlOption_NumberSignComment = 2,
	SqlOption_BackslashEscapes = 4,
	SqlOption_AllowDottedWord = 8,
	SqlOption_Default = SqlOption_BackticksIdentifier | SqlOption_NumberSignComment | SqlOption_BackslashEscapes,
};

constexpr bool IsSqlWordChar(int ch, SqlOption option) noexcept {
	return IsAlphaNumeric(ch) || ch == '_' || ((option & SqlOption_AllowDottedWord) && ch == '.');
}

constexpr bool IsANumberChar(int ch, int chPrev) noexcept {
	return IsADigit(ch) || (ch == '.' && chPrev != '.')
		|| ((ch == '+' || ch == '-') && (chPrev == 'e' || chPrev == 'E'))
		|| ((ch == 'e' || ch == 'E') && IsADigit(chPrev));
}

constexpr int GetQuoteComplement(int ch) noexcept {
	if (ch == '(') {
		return ')';
	}
	if (ch == '<') {
		return '>';
	}
	if (AnyOf<'[', '{'>(ch)) {
		return ch + 2;
	}
	return ch;
}

